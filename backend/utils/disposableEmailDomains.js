/**
 * Checks whether an email or domain belongs to known disposable/temporary providers.
 * @param {string} emailOrDomain 
 * @returns {boolean}
 */
export function isDisposableEmail(emailOrDomain) {
  if (!emailOrDomain || typeof emailOrDomain !== 'string') return false;
  
  const trimmed = emailOrDomain.toLowerCase().trim();
  const domain = trimmed.includes('@') ? trimmed.split('@').pop() : trimmed;
  
  if (!domain) return false;
  
  // Direct domain match
  if (DISPOSABLE_DOMAINS.has(domain)) return true;
  
  // Subdomain match (e.g. sub.mailinator.com)
  const parts = domain.split('.');
  if (parts.length > 2) {
    const parentDomain = parts.slice(-2).join('.');
    if (DISPOSABLE_DOMAINS.has(parentDomain)) return true;
  }
  
  return false;
}

export default isDisposableEmail;
